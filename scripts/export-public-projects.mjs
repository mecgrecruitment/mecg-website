import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

function isObject(value) {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

function approvedText(field, label) {
  if (!isObject(field) || field.approved !== true || typeof field.value !== "string" || field.value.trim() === "") {
    throw new Error(`${label} must contain approved, non-empty text.`);
  }

  return field.value.trim();
}

function approvedItems(field, label, required = true) {
  if (!Array.isArray(field)) {
    if (!required) return [];
    throw new Error(`${label} must be an array.`);
  }

  const items = field
    .filter((item) => isObject(item) && item.approved === true)
    .map((item) => approvedText(item, label));

  if (required && items.length === 0) {
    throw new Error(`${label} must include at least one approved item.`);
  }

  return items;
}

function optionalApprovedText(field, label) {
  if (field === undefined || field === null || field.approved !== true) return undefined;
  return approvedText(field, label);
}

function releaseProject(record, index) {
  if (!isObject(record)) throw new Error(`Record ${index + 1} must be an object.`);
  if (record.status !== "publishable") return undefined;
  if (typeof record.boardApprovedAt !== "string" || record.boardApprovedAt.trim() === "") {
    throw new Error(`Record ${index + 1} is missing board approval.`);
  }
  if (typeof record.clientApprovedAt !== "string" || record.clientApprovedAt.trim() === "") {
    throw new Error(`Record ${index + 1} is missing client approval.`);
  }

  const clientLabel = record.clientName?.approved === true
    ? approvedText(record.clientName, "clientName")
    : approvedText(record.anonymousLabel, "anonymousLabel");
  const handoff = optionalApprovedText(record.handoff, "handoff");

  const project = {
    slug: approvedText(record.slug, "slug"),
    title: approvedText(record.title, "title"),
    clientLabel,
    industry: approvedText(record.industry, "industry"),
    semester: approvedText(record.semester, "semester"),
    decision: approvedText(record.decision, "decision"),
    methods: approvedItems(record.methods, "methods"),
    deliverables: approvedItems(record.deliverables, "deliverables"),
    context: approvedText(record.context, "context"),
    constraints: approvedItems(record.constraints, "constraints", false),
    memberWork: approvedItems(record.memberWork, "memberWork"),
  };

  if (handoff) project.handoff = handoff;
  return project;
}

export function buildPublicProjects(input) {
  if (!Array.isArray(input)) throw new Error("Project review data must be an array.");

  const projects = input
    .map(releaseProject)
    .filter((project) => project !== undefined);
  const slugs = new Set();

  for (const project of projects) {
    if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(project.slug)) {
      throw new Error(`Invalid public project slug: ${project.slug}`);
    }
    if (slugs.has(project.slug)) throw new Error(`Duplicate public project slug: ${project.slug}`);
    slugs.add(project.slug);
  }

  return projects;
}

export function serializePublicProjects(projects) {
  return `import type { PublicProjectDetail } from "@/lib/projects/public-types";\n\n// Generated by scripts/export-public-projects.mjs. Do not add review notes or private source data.\nexport const PUBLIC_PROJECTS: readonly PublicProjectDetail[] = ${JSON.stringify(projects, null, 2)};\n`;
}

async function main() {
  const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
  const inputPath = path.resolve(repositoryRoot, process.argv[2] ?? ".audit/project-content/projects.review.json");
  const outputPath = path.resolve(repositoryRoot, process.argv[3] ?? "src/content/projects.public.ts");
  const input = JSON.parse(await readFile(inputPath, "utf8"));
  const projects = buildPublicProjects(input);

  await writeFile(outputPath, serializePublicProjects(projects), "utf8");
  process.stdout.write(`Released ${projects.length} public project${projects.length === 1 ? "" : "s"}.\n`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((error) => {
    process.stderr.write(`${error instanceof Error ? error.message : "Project export failed."}\n`);
    process.exitCode = 1;
  });
}
