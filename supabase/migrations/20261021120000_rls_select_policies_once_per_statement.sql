-- Row-level security SELECT policies that compute actor-dependent facts once
-- per statement instead of once per row.
--
-- Every rush SELECT policy used to call SECURITY DEFINER helpers per candidate
-- row (has_cycle_role, owns_application, actor_has_application_conflict and so
-- on), each re-running rush.actor_id() and its own lookup. SECURITY DEFINER
-- blocks inlining, so nothing was shared across rows: a Board listing of 260
-- applications with pnm names cost 455 ms and 18,030 buffer hits on production.
--
-- Each helper call f(x) below is replaced by `x in (select S_f())` where S_f is
-- the same SECURITY DEFINER predicate with its argument unbound, and bare
-- rush.actor_id() by (select rush.actor_id()). Postgres plans an uncorrelated
-- sublink once per statement (InitPlan or hashed SubPlan), so each row costs a
-- hash probe. f(NULL) was false while `NULL in (non-empty set)` is NULL, so a
-- call under NOT is wrapped in coalesce(..., false). Every set is NULL-free
-- (each selected column is NOT NULL). Direct table references inside policy
-- subqueries keep their shape so the nested RLS still applies as before.
--
-- The scalar helpers stay: RPC functions and storage policies still call them.
--
-- Generated by scripts/rls-initplan/generate-migration.py from the live
-- catalog of the preceding migrations. Equivalence is proven by
-- scripts/rls-initplan/verify-equivalence.sh.

create or replace function rush.actor_cycles_with_role(allowed_roles rush.member_role[])
returns setof text
language sql
stable
security definer
set search_path = ''
rows 8
as $$
  select m.cycle_id
  from rush.memberships m
  join rush.profiles p on p.id = m.user_id
  where m.user_id = (select rush.actor_id())
    and m.active
    and p.active
    and m.role = any (allowed_roles);
$$;

create or replace function rush.actor_cycles_with_capability(capability text)
returns setof text
language sql
stable
security definer
set search_path = ''
rows 8
as $$
  select m.cycle_id
  from rush.memberships m
  join rush.profiles p on p.id = m.user_id
  join rush.rush_cycles c on c.id = m.cycle_id
  where m.user_id = (select rush.actor_id())
    and m.active
    and p.active
    and (
      m.role in ('BOARD', 'OWNER')
      or (
        m.role::text = 'RECRUITMENT_COMMITTEE'
        and c.status not in ('CLOSED', 'ARCHIVED')
        and capability in ('APPLICANT_OPERATIONS', 'SCREENING_ADMINISTRATION', 'EVENTS', 'CASE_GROUPS', 'CANDIDATE_ACCESS', 'AUDIT_READ')
      )
    );
$$;

create or replace function rush.actor_active_screening_reviewer_cycles()
returns setof text
language sql
stable
security definer
set search_path = ''
rows 4
as $$
  select distinct b.cycle_id
  from rush.screening_reviewers sr
  join rush.screening_batches b on b.id = sr.batch_id
  where sr.reviewer_id = (select rush.actor_id())
    and sr.active
    and b.status = 'PUBLISHED'
    and rush.is_eligible_screening_reviewer(b.cycle_id, (select rush.actor_id()));
$$;

